-- colorless: the desktop palette, applied to Neovim.
--
-- Deliberately low-chroma: slate background, soft ink for text, one cyan accent
-- and a pale lavender for keywords. See lua/theprimeagen/palette.lua for where
-- the values come from (the same theme used by kitty, yazi, cava, GTK, ...).

local p = require("theprimeagen.palette")

local function blend(fg, bg, alpha)
  local function rgb(c)
    return tonumber(c:sub(2, 3), 16), tonumber(c:sub(4, 5), 16), tonumber(c:sub(6, 7), 16)
  end
  local fr, fgc, fb = rgb(fg)
  local br, bgc, bb = rgb(bg)
  local function mix(a, b)
    return math.floor(a * alpha + b * (1 - alpha) + 0.5)
  end
  return string.format("#%02x%02x%02x", mix(fr, br), mix(fgc, bgc), mix(fb, bb))
end

